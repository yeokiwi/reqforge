// Reads the copy deck out of docs/specs/10-ui-reference.md §13 (RD-037: the deck is a
// contract and strings are never inlined in components). The spec is the single source;
// src/copy/deck.generated.ts is derived from it and a test fails if the two drift.

export type Deck = Readonly<Record<string, string>>;

const SECTION_START = /^## 13\. Copy deck\s*$/;
const SECTION_END = /^## \d+\./;
const ID_CELL = /^`([^`]+)`(?:\s*\/\s*`([^`]+)`)*$/;
const TRAILING_NOTE = /(?:^|\s+)\*\([^\n]*\)\*$/;

export class CopyDeckParseError extends Error {
  constructor(message: string, readonly line: number) {
    super(`copy deck, line ${line}: ${message}`);
    this.name = "CopyDeckParseError";
  }
}

/** `` `a.b.c` / `.d` / `.e` `` → [a.b.c, a.b.d, a.b.e]; a leading dot replaces the last segment. */
function expandIds(cell: string, line: number): string[] {
  const tokens = [...cell.matchAll(/`([^`]+)`/g)].map((m) => m[1] as string);
  const ids: string[] = [];
  for (const token of tokens) {
    if (!token.startsWith(".")) {
      ids.push(token);
      continue;
    }
    const previous = ids[ids.length - 1];
    if (previous === undefined || !previous.includes(".")) {
      throw new CopyDeckParseError(`relative id "${token}" has nothing to be relative to`, line);
    }
    ids.push(previous.slice(0, previous.lastIndexOf(".")) + token);
  }
  return ids;
}

export function parseCopyDeck(markdown: string): Deck {
  const lines = markdown.split("\n");
  const deck: Record<string, string> = {};
  let inSection = false;

  lines.forEach((raw, index) => {
    const lineNo = index + 1;
    if (SECTION_START.test(raw)) {
      inSection = true;
      return;
    }
    if (inSection && SECTION_END.test(raw)) {
      inSection = false;
      return;
    }
    if (!inSection || !raw.startsWith("|")) return;

    const cells = raw
      .replace(/^\||\|\s*$/g, "")
      .split("|")
      .map((c) => c.trim());
    const [idCell, stringCell, ...extra] = cells;
    // Header and separator rows.
    if (idCell === undefined || idCell === "Id" || /^-+$/.test(idCell)) return;
    if (!ID_CELL.test(idCell)) throw new CopyDeckParseError(`unreadable id cell: ${idCell}`, lineNo);
    if (stringCell === undefined || extra.length > 0) {
      throw new CopyDeckParseError(`expected exactly two cells, found ${cells.length}`, lineNo);
    }

    const ids = expandIds(idCell, lineNo);
    const text = stringCell.replace(TRAILING_NOTE, "");
    if (text.length === 0) throw new CopyDeckParseError(`empty string for ${ids.join(", ")}`, lineNo);

    // One row may define several ids: `a` / `.b` | A / B. A lone id keeps " / " in its text.
    const parts = ids.length > 1 ? text.split(" / ") : [text];
    if (parts.length !== ids.length) {
      throw new CopyDeckParseError(`${ids.length} ids but ${parts.length} strings in: ${stringCell}`, lineNo);
    }
    ids.forEach((id, i) => {
      if (id in deck) throw new CopyDeckParseError(`duplicate id ${id}`, lineNo);
      deck[id] = parts[i] as string;
    });
  });

  if (Object.keys(deck).length === 0) throw new CopyDeckParseError("no copy deck found", 0);
  return deck;
}

/** The text of src/copy/deck.generated.ts for a parsed deck. Stable ordering = spec order. */
export function renderDeckModule(deck: Deck): string {
  const entries = Object.entries(deck)
    .map(([id, text]) => `  ${JSON.stringify(id)}: ${JSON.stringify(text)},`)
    .join("\n");
  return [
    "// GENERATED by scripts/gen-copy-deck.ts from docs/specs/10-ui-reference.md §13.",
    "// Do not edit. Change the spec (a GUI change needs a decision-log entry, RD-037), then",
    "// run `pnpm copy:gen`.",
    "",
    "export const deck = {",
    entries,
    "} as const;",
    "",
  ].join("\n");
}
